"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { createBrowserSupabaseClient } from "../../lib/supabase/browser";
import styles from "./auth.module.css";

type Stage = "loading" | "setup" | "verify" | "error";

export function MfaSetup() {
  const router = useRouter();
  const [client] = useState(() => createBrowserSupabaseClient());
  const started = useRef(false);
  const [stage, setStage] = useState<Stage>("loading");
  const [factorId, setFactorId] = useState("");
  const [staleFactorIds, setStaleFactorIds] = useState<string[]>([]);
  const [qrCode, setQrCode] = useState("");
  const [secret, setSecret] = useState("");
  const [code, setCode] = useState("");
  const [pending, setPending] = useState(false);
  const [message, setMessage] = useState("");

  useEffect(() => {
    if (started.current) return;
    started.current = true;
    void (async () => {
      const assurance = await client.auth.mfa.getAuthenticatorAssuranceLevel();
      if (assurance.error || !assurance.data) throw new Error("ASSURANCE_UNAVAILABLE");
      if (assurance.data.currentLevel === "aal2") {
        router.replace("/");
        return;
      }
      const factors = await client.auth.mfa.listFactors();
      if (factors.error || !factors.data) throw new Error("FACTORS_UNAVAILABLE");
      const verified = factors.data.totp[0];
      if (verified) {
        setFactorId(verified.id);
        setStage("verify");
        return;
      }
      setStaleFactorIds(factors.data.all.filter((factor) => factor.factor_type === "totp" && factor.status !== "verified").map((factor) => factor.id));
      setStage("setup");
    })().catch(() => {
      setMessage("Tidak dapat memeriksa keamanan akun. Muat ulang halaman atau hubungi admin DIV RST.");
      setStage("error");
    });
  }, [client, router]);

  async function beginEnrollment() {
    setPending(true); setMessage("");
    try {
      for (const staleFactorId of staleFactorIds) {
        const removed = await client.auth.mfa.unenroll({ factorId: staleFactorId });
        if (removed.error) throw new Error("UNENROLL_FAILED");
      }
      const result = await client.auth.mfa.enroll({ factorType: "totp", friendlyName: "Material Cadang DIV RST", issuer: "PLN Material Cadang" });
      if (result.error || !result.data) throw new Error("ENROLL_FAILED");
      setFactorId(result.data.id);
      setQrCode(result.data.totp.qr_code);
      setSecret(result.data.totp.secret);
      setStage("verify");
    } catch {
      setMessage("Autentikator belum dapat disiapkan. Coba lagi atau hubungi admin DIV RST.");
    } finally {
      setPending(false);
    }
  }

  async function verify(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!/^\d{6}$/.test(code)) {
      setMessage("Masukkan kode autentikator 6 digit.");
      return;
    }
    setPending(true); setMessage("");
    try {
      const result = await client.auth.mfa.challengeAndVerify({ factorId, code });
      if (result.error) throw new Error("VERIFY_FAILED");
      router.replace("/");
      router.refresh();
    } catch {
      setMessage("Kode tidak dapat diverifikasi. Periksa waktu perangkat dan coba lagi.");
    } finally {
      setPending(false);
    }
  }

  if (stage === "loading") return <p role="status">Memeriksa keamanan akun…</p>;
  if (stage === "error") return <p role="alert" className={styles.feedback}>{message}</p>;
  if (stage === "setup") return <div className={styles.form}>
    <h2>Aktifkan autentikator</h2>
    <p>Admin DIV RST wajib menggunakan verifikasi dua langkah.</p>
    <button type="button" className="button button--primary" disabled={pending} onClick={() => void beginEnrollment()}>
      {pending ? "Menyiapkan…" : "Siapkan autentikator"}
    </button>
    {message && <p role="alert" className={styles.feedback}>{message}</p>}
  </div>;

  return <form className={styles.form} onSubmit={verify} aria-label="Verifikasi autentikator">
    <h2>Verifikasi autentikator</h2>
    {qrCode && <div className={styles.mfaEnrollment}>
      {/* QR is generated by Supabase Auth for this one-time TOTP enrollment. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={qrCode} alt="QR autentikator" className={styles.qrCode} />
      <p>Jika QR tidak dapat dipindai, masukkan kunci ini secara manual:</p>
      <code className={styles.secret}>{secret}</code>
    </div>}
    <div className={styles.field}>
      <label htmlFor="mfa-code">Kode autentikator 6 digit</label>
      <input id="mfa-code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6}
        value={code} onChange={(event) => setCode(event.target.value.replace(/\D/g, "").slice(0, 6))} required />
    </div>
    <button type="submit" className="button button--primary" disabled={pending}>{pending ? "Memverifikasi…" : "Verifikasi dan lanjutkan"}</button>
    {message && <p role="alert" className={styles.feedback}>{message}</p>}
  </form>;
}
